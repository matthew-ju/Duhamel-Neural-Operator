#!/usr/bin/env python3
"""make_duhamel_macros.py -- write numbers_duhamel.tex for the camera-ready (Duhamel framing).

Two sources, neither typed by hand:
  * single material (the reviewed alpha = -2e9 set, 20 held-out trajectories, median over checkpoints):
      ../tdgl_tangent_eval.json   (Duhamel model, two training runs, 15 snapshots each)
      ../tdgl_frame_table.json    (same protocol: tangent, FSSM->FNO hand-off pipeline, FNO alone)
  * multi-material D1/D2 (alpha, beta, gamma and unseen noise): the macro files that
    ../paper_tools/make_figs.py etc. write from the benchmark result files. They are copied verbatim.
Rerun after any of those change:  python make_duhamel_macros.py
"""
import json
import os
import statistics as st

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
NPJ = os.path.join(ROOT, "paper_tools")


def fmt(x, nd):
    return f"{x:.{nd}f}"


def sci(x):
    m, e = f"{x:.1e}".split("e")
    return rf"{m}\times10^{{{int(e)}}}"


out = ["% AUTO-GENERATED by make_duhamel_macros.py -- do not edit by hand.\n"]

# ---- single material: per-frame table, median over checkpoint snapshots ----------------------
ft = json.load(open(os.path.join(ROOT, "tdgl_frame_table.json")))
arms = {"du": "tangent", "ho": "pipeline", "fo": "fno_alone"}
keys = {"CorrOne": "corr1", "RelOne": "rel1", "CorrFive": "corr5", "RelFive": "rel5",
        "RelFifty": "rel50", "CorrTwoH": "corr200", "RelTwoH": "rel200",
        "CorrFourH": "corr400", "RelFourH": "rel400"}
for tag, arm in arms.items():
    L = ft[arm]
    out.append(f"% {arm}: median over {len(L)} checkpoint snapshots\n")
    out.append(f"\\newcommand{{\\s{tag}N}}{{{len(L)}}}\n")
    for name, k in keys.items():
        v = st.median(x[k] for x in L)
        s = sci(v) if (k.startswith("rel") and v < 1e-3) else fmt(v, 4 if k.startswith("corr") else 3)
        out.append(f"\\newcommand{{\\s{tag}{name}}}{{{s}}}\n")

# saturation-phase RMSE (frames 100..400 step 10, top layer), same scorer (tdgl_early.score) for all arms:
# hand-off pipeline and FNO alone from tdgl_early.json, Duhamel model from tdgl_tangent_eval.json.
early = json.load(open(os.path.join(ROOT, "tdgl_early.json")))
for tag, arm in [("ho", "pipeline"), ("fo", "fno_alone")]:
    out.append(f"\\newcommand{{\\s{tag}SatRMSE}}{{{fmt(st.median(x['sat_rmse'] for x in early[arm]), 3)}}}\n")
te = json.load(open(os.path.join(ROOT, "tdgl_tangent_eval.json")))["summary"]
for run, tag in [("tdgl_tangent_eq30", "One"), ("tdgl_tangent_eq30_r2", "Two")]:
    s = te[run]
    out.append(f"\\newcommand{{\\sduRun{tag}CorrFourH}}{{{fmt(s['corr400']['median'], 4)}}}\n")
    out.append(f"\\newcommand{{\\sduRun{tag}SatRMSE}}{{{fmt(s['sat_rmse']['median'], 3)}}}\n")
sat = st.median([te["tdgl_tangent_eq30"]["sat_rmse"]["median"], te["tdgl_tangent_eq30_r2"]["sat_rmse"]["median"]])
out.append(f"\\newcommand{{\\sduSatRMSE}}{{{fmt(sat, 3)}}}\n")

# ---- per-subset zero-shot accuracy (mean over the three training seeds) and speed -------------
PH = os.path.join(ROOT, "bench", "results_phys")
subs = {}
for sd in (0, 1, 2):
    f = os.path.join(PH, "tdgl_duhamel_uno_lr0.0003_recipe_s%d.json" % sd)
    if not os.path.exists(f):
        continue
    for sp, S in json.load(open(f))["sets"].items():
        for g, v in S["subsets"].items():
            subs.setdefault(g, []).append((v["rel_t400"], v["corr_t400"], v["n"]))
names = {"interp": "Interp", "extrap": "Extrap", "A_train": "DA", "B_units": "DBunits", "B_alpha": "DBalpha",
         "C_shape": "DC", "D_all": "DD"}
for g, vs in subs.items():
    out.append(f"\\newcommand{{\\sub{names[g]}Rel}}{{{fmt(np.mean([v[0] for v in vs]), 3)}}}\n")
    out.append(f"\\newcommand{{\\sub{names[g]}Corr}}{{{fmt(np.mean([v[1] for v in vs]), 3)}}}\n")
    out.append(f"\\newcommand{{\\sub{names[g]}N}}{{{vs[0][2]}}}\n")
spd = json.load(open(os.path.join(PH, "speed.json")))
out.append(f"\\newcommand{{\\spFerroxMed}}{{{spd['ferrox_s_median']:.0f}}}\n")
out.append(f"\\newcommand{{\\spFerroxLo}}{{{spd['ferrox_s_range'][0]:.0f}}}\n")
out.append(f"\\newcommand{{\\spFerroxHi}}{{{spd['ferrox_s_range'][1]:.0f}}}\n")
for lab, tag in [("Duhamel-UNO (ours)", "Du"), ("F-FNO + recipe", "Ffno"), ("UNO + recipe", "Uno"), ("FNO + recipe", "Fno")]:
    r = spd["models"][lab]
    out.append(f"\\newcommand{{\\sp{tag}Params}}{{{r['params'] / 1e6:.1f}}}\n")
    out.append(f"\\newcommand{{\\sp{tag}Bone}}{{{r['s_per_traj_b1']:.2f}}}\n")
    out.append(f"\\newcommand{{\\sp{tag}Bsixteen}}{{{r['s_per_traj_b16']:.2f}}}\n")
    out.append(f"\\newcommand{{\\sp{tag}SpeedBone}}{{{r['speedup_b1']:.0f}}}\n")
    out.append(f"\\newcommand{{\\sp{tag}SpeedBsixteen}}{{{r['speedup_b16']:.0f}}}\n")

# ---- multi-material: the npj_v2 macro files, verbatim ----------------------------------------
for f in ["numbers.tex", "numbers_adv.tex", "numbers_old.tex", "numbers_units.tex", "numbers_pbench.tex"]:
    p = os.path.join(NPJ, f)
    out.append(f"% ---- copied from paper_tools/{f}\n")
    out.append(open(p).read().rstrip() + "\n")

open(os.path.join(HERE, "numbers_duhamel.tex"), "w").write("".join(out))

# ---- multi-material tables and figures, copied verbatim from paper_tools -------------------
import shutil
os.makedirs(os.path.join(HERE, "tables"), exist_ok=True)
os.makedirs(os.path.join(HERE, "figures", "06_duhamel"), exist_ok=True)
# main accuracy table: baselines are named plainly (every baseline uses the same training setup; see caption)
t = open(os.path.join(NPJ, "tables", "tdgl_compact.tex")).read().replace(" + recipe", "").replace(r"\ $\uparrow$", "").replace(r" $\uparrow$", "").replace(r" $\downarrow$", "")
# the best generative / pretrained model is listed with the other baselines (no separate block), under a short name
t = t.replace("\\midrule\nbest generative / pretrained (Poseidon-T)", "Poseidon-T (pretrained)")
open(os.path.join(HERE, "tables", "tdgl_compact.tex"), "w").write(t)

# physical-quantities table: see make_physics_table.py
for f in ["schematic.pdf"]:  # error_vs_time.pdf: make_evt_fig.py
    shutil.copy2(os.path.join(NPJ, "figures", f), os.path.join(HERE, "figures", "06_duhamel", f))
print("wrote numbers_duhamel.tex")
